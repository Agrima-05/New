      ,[AgentName] as [NMLSAgentName]
      ,[LenderNMLSID] as [NMLSLenderID]
      ,[LenderName] as [NMLSLenderName]
	  ,[TransactionID] 
	  ,m.[Ref_ID]
	  ,m.[PropertyID]
	  ,p.SubdivisionName
	  ,m.UpdateDate
	  ,p.[SitusStdHouseNbr]
	  ,p.[SitusStdHouseNbrSuffix]
	  ,p.[SitusStdDirectionLeft]
	  ,p.[SitusStdStreet]
	  ,p.[SitusStdMode]
	  ,p.[SitusStdDirectionRight]
	  ,p.[SitusStdUnitType]
	  ,p.[SitusStdUnitNbr]
	  ,m.[FATimestamp]
	  ,m.[FAUCIDFlag]
	  ,m.[MarketShare]
	  ,m.[LoanIntRate]
	  ,[Listing_Agent_Name]
	  ,[Listing_Agent_Address]
	  ,[Listing_Agent_Phone]
	  ,[Listing_Agent_Email]
	  ,[Office_Name]
	  ,[Office_Address]
	  ,[Office_Phone]
	  ,[Office_Email]	
	  ,a.[final_value] as AVMvalue
	  ,a.[VALUATION_DATE] as ValuationDate
FROM [MarketShare].[dbo].[bulkMKSHR_ALL] m with(NOLOCK) LEFT OUTER JOIN [Data].[dbo].[Property] p with(NOLOCK)
on m.[PropertyID] = p.[PropertyID]
LEFT OUTER JOIN Data.dbo.[AVM] a with(NOLOCK) ON a.Fips = p.FIPS and a.PropertyID = p.PropertyID

