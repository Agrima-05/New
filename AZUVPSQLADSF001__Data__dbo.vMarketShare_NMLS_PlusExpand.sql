      ,[FMT_Book_Page] as [SaleBookPage]
      ,[FMT_MTG1_DOC_NBR] as [MtgDocNbr]
      ,[FMT_MTG1_Book_Page] as [MtgBookPage]
      ,CASE WHEN isNULL([FMT_MTG1_DOC_NBR],'') like '' THEN [FMT_MTG1_Book_Page] ELSE [FMT_MTG1_DOC_NBR] END as [MtgDocNumBkPg]
      ,m.[DeedID]
      ,[Transaction Type]
      ,[Loan To Value]
      ,[Adjustable Rate]
      ,[Loan Type]
      ,[Reverse Mortgage]
      ,[Conforming]
      ,[Seller Name]
      ,[Buyer] as [Buyer Name]
