CREATE VIEW [dbo].[vMarketShare_NMLS_PlusExpand]
AS
Select Distinct Substring(cast(m.[Date] as varchar),1,7) as [YearMonth]
      ,m.[FIPSCode] as Fips
      ,[Zip Code]
      ,[County]
      ,[State]
      ,[Title Company]
      ,[Title Company Clean]
      ,[Transaction Type Clean]
      ,[Property Type]
	  ,case when [Property Type] In ('Single Family Residence', 'Duplex (Triplex, Quadplex)', 'Condominium') then 'Residential' else 'Other' end as [Property Type RES OTHER]
