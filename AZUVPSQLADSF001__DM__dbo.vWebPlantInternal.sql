CREATE VIEW [dbo].[vWebPlantInternal]
AS
/****** Script for SelectTopNRows command from SSMS  ******/

SELECT Id
	  ,[County Code]
      ,[FIPS Code]
      ,PlantType
      ,[Count]
      ,[Tier]
      ,[County Priority]
      ,[Plant Date]
      ,[In House Days - GF]
      ,[Xmit'd Days - GF]
      ,[Recv'd Days]
      ,[Working Days Out]
      ,[DE Vendor]
      ,[Vendor TAT]
      ,[TAT Explanation]
      ,[ETC - Days Over (past 5 xmits)]
      ,[Days Behind ETC (for current date)]
      ,[Data Tree Image Date]
      ,[Latest County Source]
      ,[Comment]
      ,[Total # Missing Images]
      ,[Total Recorded Docs for Held Date]
      ,[PQ Number]
      ,[Plat Vendor]
      ,[Compliance Date]
      ,[Source Frequency]
      ,[Grantor/Grantee Thru Date]
      ,[FL Geographical Thru Date]
      ,[Courthouse Date]
      ,[Courthouse Source Thru Date]
      ,[Courthouse Source Comments]
      ,[UR LIVE Date]
      ,[UR LIVE Recording Date]
      ,[UR LIVE XMIT Date]
      ,[QA Vendor]
      ,[Exception Reports - GF]
      ,[Oldest Exception Report Date]
      ,[PI Plant Date]
      ,[RV Plant Date]
      ,[Fund Plant Date]
      ,[Geo County]
      ,[Geo County Status]
      ,[Modified]
      ,[Modified By]
      ,[DE Matrix]
      ,[Item Type]
      ,[Path]
	  ,a.[Thru Inst Date]
      ,a.[Region]
      ,a.[Thru Date(TOR / TEE)]
      ,a.[Thru Inst Date(TOR / TEE)]
      ,a.[Thru Date(Geographic )]
      ,a.[Thru Inst Date(Geographic)]
      ,a.[Courthouse Source Xmit Date]
	  ,a.[Working Days Out Compliance Standard]
	  ,a.[ImageDataSourceComments]
	   from (
SELECT 
	  ROW_NUMBER() OVER (PARTITION BY s.[FIPS Code] order by s.[Plant Date] desc) rowNum	
	  ,s.Id  
      ,s.[County Code]
      ,s.[FIPS Code]
      ,s.[Count]
      ,s.[Tier]
      ,s.[County Priority]
      ,s.[Plant Date]
      ,s.[In House Days - GF]
      ,s.[Xmit'd Days - GF]
      ,s.[Recv'd Days]
      ,s.[Working Days Out]
      ,s.[DE Vendor]
      ,s.[Vendor TAT]
      ,s.[TAT Explanation]
      ,s.[ETC - Days Over (past 5 xmits)]
      ,s.[Days Behind ETC (for current date)]
      ,s.[Data Tree Image Date]
      ,s.[Latest County Source]
      ,s.[Comment]
      ,s.[Total # Missing Images]
      ,s.[Total Recorded Docs for Held Date]
      ,s.[PQ Number]
      ,s.[Plat Vendor]
      ,s.[Compliance Date]
      ,s.[Source Frequency]
      ,s.[Grantor/Grantee Thru Date]
      ,s.[FL Geographical Thru Date]
      ,s.[Courthouse Date]
      ,s.[Courthouse Source Thru Date]
      ,s.[Courthouse Source Comments]
      ,s.[UR LIVE Date]
      ,s.[UR LIVE Recording Date]
      ,s.[UR LIVE XMIT Date]
      ,s.[QA Vendor]
      ,s.[Exception Reports - GF]
      ,s.[Oldest Exception Report Date]
      ,s.[PI Plant Date]
      ,s.[RV Plant Date]
      ,s.[Fund Plant Date]
      ,s.[Geo County]
      ,s.[Geo County Status]
      ,s.[Modified]
      ,s.[Modified By]
      ,s.[DE Matrix]
      ,s.[Item Type]
      ,s.[Path]
      ,s.[Thru Inst Date]
      ,s.[Region]
      ,s.[Thru Date(TOR / TEE)]
      ,s.[Thru Inst Date(TOR / TEE)]
      ,s.[Thru Date(Geographic )]
      ,s.[Thru Inst Date(Geographic)]
      ,s.[Courthouse Source Xmit Date]
	  ,s.[Working Days Out Compliance Standard]
	  ,s.[ImageDataSourceComments]
	  ,s.[PlantType]
  FROM  ScoreCard s  
  where [PlantType] = 'Internal'
  ) a 
 -- left join County c on a.[FIPS Code] = c.FIPSCode
  where RowNum = 1   

