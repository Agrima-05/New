Create VIEW [dbo].[vListingHistory_20180628]
AS
	SELECT
		l.Listing_ID
		,l.UPDATE_FLAG_DATE_STD
		,l.UpdateSeq
		,l.UpdateTimestamp
		,s.*
		,DATEDIFF(DAY, MLS_LIST_DATE_STD, CASE WHEN MLS_STATUS_STD = 'Fail' THEN CASE WHEN l.UPDATE_FLAG_DATE_STD >= '2000-01-01' THEN l.UPDATE_FLAG_DATE_STD END ELSE ISNULL(SOLD_DATE_STD, CASE WHEN UpdateSeq < CurrentUpdateSeq THEN CASE WHEN l.UPDATE_FLAG_DATE_STD >= '2000-01-01' THEN l.UPDATE_FLAG_DATE_STD END ELSE GETDATE() END) END) AS MLS_DAYS_ON_MARKET_STD
		,ISNULL(SOLD_PRICE_STD, MLS_LIST_PRICE_STD) / HOME_SIZE_STD AS PRICE_PER_SQFT_STD
	FROM ListingHistory l WITH (NOLOCK)
	CROSS APPLY dbo.fnGetListingSnapshotSingle(UPDATE_FLAG_DATE_STD, UpdateSeq, Listing_ID) s


